export type LessonType = "video" | "article" | "interactive" | "practice" | "project" | "quiz";

export interface LessonMedia {
  /** Optional published YouTube/Vimeo URL or direct .mp4/.webm asset. */
  video?: string;
  /** Optional compact study notes URL. Hidden until provided. */
  notes?: string;
  /** Optional PDF URL for printable/offline study. Hidden until provided. */
  pdf?: string;
}

export interface Lesson {
  title: string;
  type: LessonType;
  duration: string;
  href?: string;
  media?: LessonMedia;
}

export interface RecallQA {
  q: string;
  a: string;
}

export interface CourseModule {
  title: string;
  phase: string;
  hook: string;
  feynman: string;
  lessons: Lesson[];
  recall: RecallQA[];
}

export interface Course {
  slug: string;
  title: string;
  tagline: string;
  description: string;
  level: "Beginner" | "Intermediate" | "Advanced" | "All Levels";
  duration: string;
  category: string;
  icon: string;
  outcomes: string[];
  modules: CourseModule[];
  featured?: boolean;
}

const V = (title: string, duration: string, href?: string): Lesson => ({ title, type: "video", duration, href });
// YV binds an external video reference directly to its StackShade lesson.
const YV = (title: string, duration: string, video: string): Lesson => ({ title, type: "video", duration, media: { video } });
const A = (title: string, duration: string, href?: string): Lesson => ({ title, type: "article", duration, href });
const I = (title: string, duration: string, href?: string): Lesson => ({ title, type: "interactive", duration, href });
const P = (title: string, duration: string, href?: string): Lesson => ({ title, type: "practice", duration, href });
const PJ = (title: string, duration: string): Lesson => ({ title, type: "project", duration });

